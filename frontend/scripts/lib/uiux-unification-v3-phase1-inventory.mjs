function readRouteContract(repo) {
  const text = fs.readFileSync(path.join(repo, 'frontend/src/router/uiRouteContract.ts'), 'utf8')
  const paths = [...text.matchAll(/path: '([^']+)'/g)].map((item) => item[1])
  const scopes = [...text.matchAll(/v2Scope: UI_V2_SCOPE\.([A-Z]+)/g)].map((item) => item[1].toLowerCase())
  const protections = [...text.matchAll(/protection: UI_ROUTE_PROTECTION\.([A-Z]+)/g)].map((item) =>
    item[1].toLowerCase(),
  )
  const count = (values) =>
    values.reduce((acc, value) => {
      acc[value] = (acc[value] || 0) + 1
      return acc
    }, {})
  return {
    paths,
    scopeCount: count(scopes),
    protectionCount: count(protections),
    offPaths: paths.filter((_, index) => scopes[index] === 'off'),
    mixedPaths: paths.filter((_, index) => protections[index] === 'mixed'),
  }
}

