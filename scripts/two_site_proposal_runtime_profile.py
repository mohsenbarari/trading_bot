def validate_role_metadata(data: bytes, profile: PreparedProfile) -> None:
    """Complete known selected/resolved/prompt/tool/permission envelopes."""
    try:
        if type(data) is not bytes or not (1 <= len(data) <= MAX_METADATA):
            raise ValueError()
        singleton_shape(data, {k: 2 for k in (1, 2, 3, 4, 6, 7, 10, 18)})
        selected = one(data, 4)
        singleton_shape(selected, {1: 2, 7: 2, 8: 2, 12: 0, 13: 0, 15: 0})
        resolved = one(data, 10)
        singleton_shape(resolved, {5: 2, 11: 2, 17: 2, 18: 2})
        singleton_shape(one(resolved, 17), {16: 2})
        singleton_shape(one(resolved, 18), {1: 2, 3: 2, 4: 2})
        singleton_shape(one(selected, 7), {5: 2, 11: 2, 18: 2})
        container = expected_tool_container()
        configuration = message(
            (1, container), (3, AUX),
            (4, FLAGS + message((8, profile.source.as_uri()), (9, b"\x08\x01"))),
        )
        expected_selected = message((5, "off"), (11, AUX), (18, configuration))
        expected = message(
            (5, "off"), (11, AUX), (17, message((16, profile.source.as_uri()))),
            (18, configuration),
        )
        if (
            one(selected, 1) != NAME.encode() or one(selected, 8) != DESCRIPTION.encode()
            or one(selected, 12) != 0 or one(selected, 13) != 1 or one(selected, 15) != 1
            or fields(one(selected, 7)) != fields(expected_selected)
            or fields(resolved) != fields(expected)
            or one(data, 6) != profile.conversation_id.encode()
            or one(data, 7) != profile.workspace.as_uri().encode()
        ):
            raise ValueError()
    except (ValueError, TypeError, AttributeError):
        raise ProposalProfileError("proposal runtime profile metadata mismatch") from None


def _regular(path: Path, limit: int) -> tuple[int, int]:
    try:
        st = path.lstat()
        if (
            not stat.S_ISREG(st.st_mode) or st.st_nlink != 1
            or st.st_uid != os.geteuid() or st.st_size > limit
            or path.resolve(strict=True) != path
        ):
            raise ValueError()
        return st.st_dev, st.st_ino
    except (OSError, ValueError):
        raise ProposalProfileError("unsafe proposal runtime metadata file") from None


def validate_resource_inventory(data: bytes, profile: PreparedProfile) -> None:
    """CLI 1.4 discovery provenance; never effective tool or command authority.

    Global skill/plugin discovery is distinct from the exact executor tool container.
    Local discovery must describe only our pinned agent and two fixed hooks.
    """
    if type(data) is not bytes or not 1 <= len(data) <= 65536:
        raise ValueError("invalid proposal runtime resource inventory")
    rows = wire_fields(data)
    if not 1 <= len(rows) <= 128:
        raise ValueError("invalid proposal runtime resource count")
    local = set()
    seen = set()
    for number, wire, row in rows:
        if number != 1 or wire != 2:
            raise ValueError("invalid proposal runtime resource envelope")
        singleton_shape(row, {1: 0, 2: 2, 3: 2, 4: 0, 5: 0}, {6: 2})
        kind, label, source, origin, enabled = (one(row, k) for k in (1, 2, 3, 4, 5))
        if (kind not in (3, 4, 5, 6) or enabled != 1
                or not 1 <= len(label) <= 256 or not 1 <= len(source) <= 4096
                or (one(row, 6) is not None and len(one(row, 6)) > 64)
                or (kind, label) in seen):
            raise ValueError("invalid proposal runtime resource record")
        seen.add((kind, label))
        if kind in (3, 5):
            if origin != 2:
                raise ValueError("unexpected local skill or plugin resource")
        else:
            if origin != 3:
                raise ValueError("unexpected agent or hook resource origin")
            local.add((kind, label, source))
    hooks = str(profile.workspace / ".agents/hooks.json").encode()
    if local != {(4, NAME.encode(), str(profile.source).encode()),
                 (6, b"proposal-only", hooks), (6, b"proposal-single-invocation", hooks)}:
        raise ValueError("proposal runtime local resource mismatch")


def validate_profile(
    profile: PreparedProfile, *, fresh: bool, cli_home: Path | None = None,
    deadline: float | None = None,
) -> dict:
    """Bind only the exact prepared session; legacy callers retain five-second waits."""
    _budget_remaining(deadline, 5)
    if type(profile) is not PreparedProfile or type(profile.conversation_id) is not str or not UUID.fullmatch(profile.conversation_id):
        raise ProposalProfileError("invalid proposal runtime profile identity")
    if type(fresh) is not bool or not profile.workspace.is_absolute():
        raise ProposalProfileError("invalid proposal runtime profile request")
    validate_hooks(profile.workspace)
    source_identity = _regular(profile.source, 4096)
    with profile.source.open("rb") as source:
        definition = source.read(4097)
    if definition != DEFINITION.encode() or _regular(profile.source, 4096) != source_identity:
        raise ProposalProfileError("proposal runtime definition mismatch")
    home = cli_home if cli_home is not None else Path.home()/".gemini/antigravity-cli"
    database = home/"conversations"/(profile.conversation_id+".db")
    identity = _regular(database, MAX_DATABASE)
    try:
        with closing(sqlite3.connect(database.as_uri()+"?mode=ro", uri=True,
                                             timeout=_budget_remaining(deadline, 5))) as db:
            if deadline is not None:
                db.set_progress_handler(lambda: int(time.monotonic() >= deadline), 1000)
            db.execute("PRAGMA query_only=ON"); db.execute("BEGIN")
            ids = db.execute("SELECT cascade_id,trajectory_type,source FROM trajectory_meta LIMIT 2").fetchall()
            main_count = db.execute("SELECT COUNT(*) FROM trajectory_metadata_blob WHERE id='main'").fetchone()[0]
            rows = db.execute("SELECT data FROM trajectory_metadata_blob WHERE id='main' AND typeof(data)='blob' AND length(data)<=262144 LIMIT 2").fetchall()
            if ids != [(profile.conversation_id, 4, 17)] or main_count != 1 or len(rows) != main_count:
                raise ProposalProfileError("proposal runtime database identity mismatch")
            validate_role_metadata(rows[0][0], profile)
            count = db.execute("SELECT COUNT(*) FROM steps").fetchone()[0]
            if fresh and count != 0:
                raise ProposalProfileError("proposal runtime session is not fresh")
            if not fresh:
                executor_count = db.execute("SELECT COUNT(*) FROM executor_metadata").fetchone()[0]
                if not 1 <= executor_count <= 8:
                    raise ProposalProfileError("proposal runtime executor evidence missing")
                executors = db.execute("SELECT data FROM executor_metadata WHERE typeof(data)='blob' AND length(data)<=524288 LIMIT 9").fetchall()
                if len(executors) != executor_count:
                    raise ProposalProfileError("proposal runtime executor evidence missing")
                for row in executors:
                    data = row[0]
                    singleton_shape(data, {1: 0, 2: 0, 3: 0, 9: 2, 10: 2, 11: 2, 17: 2, 18: 2})
                    validate_resource_inventory(one(data, 18), profile)
                    config = one(data, 10, 1)
                    if (
                        one(config, 28) != profile.model.encode()
                        or one(config, 46) != expected_tool_container()
                        or type(one(data, 1)) is not int or one(data, 1) != 9
                    ):
                        raise ProposalProfileError("proposal runtime actual executor mismatch")
    except ProposalProfileError:
        raise
    except (sqlite3.Error, ValueError, TypeError, AttributeError):
        raise ProposalProfileError("proposal runtime database validation failed") from None
    _budget_remaining(deadline, 5)
    if _regular(database, MAX_DATABASE) != identity:
        raise ProposalProfileError("proposal runtime database identity drift")
    validate_hooks(profile.workspace)
    return {"conversation_id": profile.conversation_id, "name": NAME,
            "native_tools": 0, "command_policy": "off", "actual_executor_checked": not fresh}


def _sessions(directory: Path) -> set[str]:
    names = set()
    try:
        with os.scandir(directory) as entries:
            for index, entry in enumerate(entries):
                if index >= MAX_DIRECTORY_ENTRIES:
                    raise ProposalProfileError("proposal runtime session directory exceeds limit")
                if entry.name.endswith(".db") and UUID.fullmatch(entry.name[:-3]):
                    names.add(entry.name)
    except OSError:
        raise ProposalProfileError("proposal runtime session directory unavailable") from None
    return names


def _new_file(path: Path, content: bytes) -> None:
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    with os.fdopen(fd, "wb") as stream:
        stream.write(content)


def trust_choice(text: str, workspace: Path) -> bytes | None:
    """Recognize only the pinned, path-bound workspace trust dialog."""
    text = re.sub(r"\x1b\[[0-?]*[ -/]*[@-~]", "", text)
    text = re.sub(r"\x1b\][^\x07\x1b]*(?:\x07|\x1b\\)", "", text)
    if "Do you trust" not in text or ("workspace" not in text.lower() and "trust this folder" not in text):
        return None
    # Terminal updates arrive incrementally. Never reject or acknowledge a
    # half-rendered dialog before its final Enter instruction has arrived.
    if re.search(r"\benter\b", text, re.IGNORECASE) is None:
        return None
    exact_path = re.search(r"(?<![A-Za-z0-9_./-])" + re.escape(str(workspace)) + r"(?![A-Za-z0-9_./-])", text)
    if exact_path is None or "Yes, I trust" not in text or "trust this folder" not in text:
        raise ProposalProfileError("proposal runtime trust scope mismatch")
    return b"1\r"


def _initialization_readiness_hint(
    directory: Path, before: set[str], workspace: Path, model: str,
    effort: str | None, *, deadline: float,
) -> tuple[bool, dict]:
    """Non-authoritative, nonblocking hint; final validate_profile still decides.

    Only this preparation's new sessions are inspected. No UI, message, auth,
    metadata payload or path is retained in the fixed count/reason observation.
    """
    names = _sessions(directory) - before
    facts = dict(reason="NOT_READY", new_sessions=len(names), valid_profiles=0,
                 empty_profiles=0, invalid_profiles=0, sqlite_unavailable=0)
    if not 1 <= len(names) <= MAX_NEW_SESSIONS:
        facts["reason"] = "NEW_SESSION_COUNT"
        return False, facts
    for name in sorted(names):
        if time.monotonic() >= deadline:
            facts["reason"] = "DEADLINE"
            return False, facts
        candidate = PreparedProfile(name[:-3], workspace, model, effort)
        database = directory / name
        try:
            identity = _regular(database, MAX_DATABASE)
            with closing(sqlite3.connect(database.as_uri() + "?mode=ro",
                                         uri=True, timeout=0)) as db:
                db.execute("PRAGMA query_only=ON")
                db.set_progress_handler(lambda: int(time.monotonic() >= deadline), 1000)
                db.execute("BEGIN")
                ids = db.execute("SELECT cascade_id,trajectory_type,source FROM trajectory_meta LIMIT 2").fetchall()
                main = db.execute("SELECT typeof(data),length(data) FROM trajectory_metadata_blob WHERE id='main' LIMIT 2").fetchall()
                used = db.execute("SELECT 1 FROM steps LIMIT 1").fetchall()
                empty = ids == [(candidate.conversation_id, 0, 0)] and main == [("blob", 0)] and not used
                if empty:
                    if db.execute("SELECT 1 FROM executor_metadata LIMIT 1").fetchone() is not None:
                        raise ProposalProfileError("proposal runtime placeholder is not pristine")
                    facts["empty_profiles"] += 1
                else:
                    if (ids != [(candidate.conversation_id, 4, 17)] or used
                            or len(main) != 1 or main[0][0] != "blob"
                            or type(main[0][1]) is not int or not 1 <= main[0][1] <= MAX_METADATA):
                        raise ProposalProfileError("proposal runtime database identity mismatch")
                    rows = db.execute("SELECT data FROM trajectory_metadata_blob WHERE id='main' AND typeof(data)='blob' AND length(data)<=262144 LIMIT 2").fetchall()
                    if len(rows) != 1:
                        raise ProposalProfileError("proposal runtime database identity mismatch")
                    validate_role_metadata(rows[0][0], candidate)
            if _regular(database, MAX_DATABASE) != identity:
                raise ProposalProfileError("proposal runtime database identity drift")
            if not empty:
                facts["valid_profiles"] += 1
        except sqlite3.Error:
            facts["sqlite_unavailable"] += 1
        except ProposalProfileError:
            facts["invalid_profiles"] += 1
    if time.monotonic() >= deadline:
        facts["reason"] = "DEADLINE"
        return False, facts
    valid = facts["valid_profiles"]
    facts["reason"] = ("READY" if valid == 1 else "AMBIGUOUS" if valid > 1
                       else "INITIAL_METADATA_EMPTY" if facts["empty_profiles"]
                       else "SQLITE_UNAVAILABLE" if facts["sqlite_unavailable"]
                       else "INVALID_METADATA")
    return valid == 1, facts


def _preparation_failure_observation(
    buffer: bytearray, process, workspace: Path, trust_accepted: bool,
    pending_trust: bool, ready_during_preparation: bool,
) -> dict:
    """Fixed diagnostics only; never retain volatile UI/prose/path or grant readiness."""
    text = buffer.decode("utf-8", errors="replace")
    normalized = re.sub(r"\x1b\[[0-?]*[ -/]*[@-~]", "", text)
    normalized = re.sub(r"\x1b\][^\x07\x1b]*(?:\x07|\x1b\\)", "", normalized)
    lower = normalized.casefold()
    code = process.poll() if process is not None else None
    state = ("NOT_STARTED" if process is None else "RUNNING" if code is None
             else "EXITED_ZERO" if type(code) is int and code == 0
             else "EXITED_NONZERO" if type(code) is int else "UNKNOWN")
    return {
        "capture_state": "CAPTURED", "ui_bytes": len(buffer),
        "process_state_before_cleanup": state,
        "trust_answer_sent": trust_accepted, "pending_trust": pending_trust,
        "ready_during_preparation": ready_during_preparation,
        "agent_not_found_label": "agent not found" in lower,
        "unknown_agent_label": "unknown agent" in lower,
        "not_found_label": "not found" in lower,
        "fixed_agent_name_present": NAME in normalized,
        "trust_marker_present": "Do you trust" in normalized,
        "owned_workspace_present": str(workspace) in normalized,
        "enter_boundary_present": re.search(r"\benter\b", normalized, re.IGNORECASE) is not None,
        "authentication_prompt_present": any(label in lower for label in (
            "sign in", "sign-in", "log in", "authentication required")),
        "network_error_present": any(label in lower for label in (
            "connection refused", "connection reset", "tls handshake timeout",
            "context deadline exceeded", "failed to connect")),
        "dependency_missing_present": any(label in lower for label in (
            "executable file not found", "command not found", "no such file or directory")),
    }



def _budget_remaining(deadline: float | None, maximum: float) -> float:
    if deadline is None:
        return maximum
    if type(deadline) not in (int, float) or not math.isfinite(deadline):
        raise ProposalProfileError("invalid proposal runtime deadline")
    remaining = deadline - time.monotonic()
    if remaining <= 0:
        raise ProposalProfileError("proposal runtime preparation budget exhausted")
    return min(maximum, remaining)


def _identity9(info) -> tuple:
    return tuple(getattr(info, key) for key in (
        "st_dev", "st_ino", "st_mode", "st_uid", "st_gid", "st_nlink",
        "st_size", "st_mtime_ns", "st_ctime_ns"))


def _persisted_snapshot(path: Path, deadline: float, limit: int, *, optional=False):
    _budget_remaining(deadline, 1)
    try:
        info = path.lstat()
    except FileNotFoundError:
        if optional:
            return None
        raise
    identity = _identity9(info)
    if (not stat.S_ISREG(info.st_mode) or info.st_uid != os.geteuid()
            or info.st_nlink != 1 or info.st_size > limit
            or path.resolve(strict=True) != path):
        raise ProposalProfileError("unsafe proposal runtime recovery file")
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC)
    try:
        if _identity9(os.fstat(fd)) != identity:
            raise ProposalProfileError("proposal runtime recovery file drift")
        digest, size = hashlib.sha256(), 0
        while True:
            _budget_remaining(deadline, 1)
            chunk = os.read(fd, min(65536, limit + 1 - size))
            if not chunk:
                break
            size += len(chunk)
            if size > limit:
                raise ProposalProfileError("proposal runtime recovery file exceeds limit")
            digest.update(chunk)
        if (size != info.st_size or _identity9(os.fstat(fd)) != identity
                or _identity9(path.lstat()) != identity):
            raise ProposalProfileError("proposal runtime recovery file drift")
        return identity, digest.hexdigest()
    finally:
        os.close(fd)


def _recovery_cli_fingerprint(cli: Path, *, deadline: float | None = None):
    """Optional identity; missing/unproved pins never change the original first flow."""
    try:
        info = cli.lstat()
        if (not stat.S_ISREG(info.st_mode) or info.st_uid != os.geteuid()
                or info.st_nlink != 1 or info.st_size != REVIEWED_CLI_BYTES
                or cli.resolve(strict=True) != cli or not os.access(cli, os.X_OK)):
            return None
    except (OSError, ValueError):
        return None
    now = time.monotonic()
    total = now + INITIALIZATION_TOTAL_BUDGET if deadline is None else deadline
    try:
        snapshot = _persisted_snapshot(cli, min(total, now + 10), REVIEWED_CLI_BYTES)
    except (OSError, ValueError):
        # A failed optional ten-second proof is NO_RECOVERY, not a fresh budget.
        # An OS read may return late; never swallow an expired overall budget.
        _budget_remaining(total, 1)
        return None, total
    _budget_remaining(total, 1)
    return (snapshot if snapshot[1] == REVIEWED_CLI_SHA256 else None), total


def _recovery_workspace(workspace: Path):
    info = workspace.lstat()
    if (workspace.resolve(strict=True) != workspace or not stat.S_ISDIR(info.st_mode)
            or info.st_uid != os.geteuid() or stat.S_IMODE(info.st_mode) != 0o700):
        raise ProposalProfileError("unsafe proposal runtime recovery workspace")
    git = workspace / ".git"
    git_info = git.lstat()
    if (git.resolve(strict=True) != git or not stat.S_ISDIR(git_info.st_mode)
            or git_info.st_uid != os.geteuid()):
        raise ProposalProfileError("unsafe proposal runtime recovery Git root")
    source = workspace / ".agents/agents" / NAME / "agent.md"
    identity = _regular(source, 4096)
    with source.open("rb") as stream:
        definition = stream.read(4097)
    if definition != DEFINITION.encode() or _regular(source, 4096) != identity:
        raise ProposalProfileError("proposal runtime definition mismatch")
    validate_hooks(workspace)
    return (info.st_dev, info.st_ino, info.st_mode, info.st_uid, info.st_gid,
            git_info.st_dev, git_info.st_ino, git_info.st_mode, git_info.st_uid)


def _inspect_shm(path: Path, deadline: float):
    _budget_remaining(deadline, 1)
    try:
        info = path.lstat()
    except FileNotFoundError:
        return
    # SHM is an ephemeral lock/index; never hash its contents/mtime as persisted data.
    if (not stat.S_ISREG(info.st_mode) or info.st_uid != os.geteuid()
            or info.st_nlink != 1 or not 0 <= info.st_size <= MAX_DATABASE
            or path.resolve(strict=True) != path
            or _identity9(path.lstat())[:7] != _identity9(info)[:7]):
        raise ProposalProfileError("unsafe proposal runtime recovery SHM")


def _pristine_initialization_snapshot(directory: Path, name: str, deadline: float):
    """Only this call's fresh empty CID; WAL-visible SQL and stable persisted bytes."""
    if not name.endswith(".db") or not UUID.fullmatch(name[:-3]):
        raise ProposalProfileError("invalid proposal runtime recovery identity")
    database = directory / name
    wal, shm = Path(str(database) + "-wal"), Path(str(database) + "-shm")
    if os.path.lexists(str(database) + "-journal"):
        raise ProposalProfileError("proposal runtime recovery journal is unresolved")
    before = (_persisted_snapshot(database, deadline, MAX_DATABASE),
              _persisted_snapshot(wal, deadline, MAX_DATABASE, optional=True))
    _inspect_shm(shm, deadline)
    _budget_remaining(deadline, 1)
    try:
        with closing(sqlite3.connect(database.as_uri() + "?mode=ro", uri=True, timeout=0)) as db:
            db.set_progress_handler(lambda: int(time.monotonic() >= deadline), 1000)
            db.execute("PRAGMA query_only=ON"); db.execute("BEGIN")
            ids = db.execute("SELECT cascade_id,typeof(cascade_id),trajectory_type,typeof(trajectory_type),source,typeof(source) FROM trajectory_meta LIMIT 2").fetchall()
            metadata = db.execute("SELECT id,typeof(id),typeof(data),length(data) FROM trajectory_metadata_blob LIMIT 2").fetchall()
            steps = db.execute("SELECT 1 FROM steps LIMIT 1").fetchall()
            executors = db.execute("SELECT 1 FROM executor_metadata LIMIT 1").fetchall()
            logical = (ids, metadata, steps, executors)
            if logical != ([(name[:-3], "text", 0, "integer", 0, "integer")],
                           [("main", "text", "blob", 0)], [], []):
                raise ProposalProfileError("proposal runtime recovery is not pristine")
    except sqlite3.Error:
        raise ProposalProfileError("proposal runtime recovery database unavailable") from None
    _budget_remaining(deadline, 1)
    _inspect_shm(shm, deadline)
    after = (_persisted_snapshot(database, deadline, MAX_DATABASE),
             _persisted_snapshot(wal, deadline, MAX_DATABASE, optional=True))
    if before != after:
        raise ProposalProfileError("proposal runtime recovery persisted state drift")
    return before, logical


def _empty_recovery_eligible(error: ProposalProfileError, report: dict) -> bool:
    facts = getattr(error, "preparation_observation", None)
    required = {
        "capture_state", "ui_bytes", "process_state_before_cleanup",
        "trust_answer_sent", "pending_trust", "ready_during_preparation",
        "agent_not_found_label", "unknown_agent_label", "not_found_label",
        "fixed_agent_name_present", "trust_marker_present", "owned_workspace_present",
        "enter_boundary_present", "authentication_prompt_present",
        "network_error_present", "dependency_missing_present",
    }
    fixed = {"capture_state", "ui_bytes", "process_state_before_cleanup"}
    return bool(
        type(facts) is dict and set(facts) == required
        and facts["capture_state"] == "CAPTURED"
        and type(facts["ui_bytes"]) is int and facts["ui_bytes"] == 0
        and facts["process_state_before_cleanup"] == "RUNNING"
        and all(facts[key] is False for key in required - fixed)
        and report.get("cleanup_normal") is True
        and report.get("descriptors_closed") is True and report.get("process_dead") is True
        and report.get("empty_seen") is True and not report.get("bad_seen")
        and not report.get("ready_seen") and report.get("final_valid_profiles") == 0
        and len(report.get("names", ())) == 1
    )


def _append_preparation_diagnostic(
    error: ProposalProfileError, *, phase: str, reason: str, attempts: int,
    report: dict, pinned: bool,
) -> None:
    """Best-effort fixed facts survive Runner's existing type+str boundary.

    No payload or underlying exception text is formatted. This never decides
    eligibility, retries a request, or replaces the original exception.
    """
    try:
        phases = {"FIRST", "PRE_SECOND", "SECOND", "FINAL"}
        reasons = {"INELIGIBLE", "BUDGET", "ROSTER", "PRISTINE", "WORKSPACE",
                   "CLI_PIN", "BUDGET_OR_ROSTER", "INITIALIZER_FAILED",
                   "FINAL_IDENTITY_STATE", "FINAL_VALIDATE", "FINAL_ROSTER_STATE"}
        if (not isinstance(error, ProposalProfileError) or phase not in phases
                or reason not in reasons or type(attempts) is not int
                or attempts not in (1, 2) or type(pinned) is not bool):
            return
        args = error.args
        if (len(args) != 1 or type(args[0]) is not str
                or len(args[0]) > 2048 or "; PREP_DIAG " in args[0]):
            return
        data = report if type(report) is dict else {}
        facts = getattr(error, "preparation_observation", None)
        facts = facts if type(facts) is dict else {}
        ui_bytes = facts.get("ui_bytes")
        ui = ("EMPTY" if type(ui_bytes) is int and ui_bytes == 0 else
              "NONEMPTY" if type(ui_bytes) is int and 0 < ui_bytes <= MAX_UI else "UNKNOWN")
        if reason == "INELIGIBLE":
            if not pinned:
                reason = "NO_PIN"
            elif any(data.get(key) is not True for key in (
                    "cleanup_normal", "descriptors_closed", "process_dead")):
                reason = "CLEANUP_UNCERTAIN"
            elif facts.get("capture_state") != "CAPTURED":
                reason = "DIAGNOSTICS_UNAVAILABLE"
            elif ui != "EMPTY":
                reason = "UI_NONEMPTY" if ui == "NONEMPTY" else "UI_UNKNOWN"
            elif facts.get("process_state_before_cleanup") != "RUNNING":
                reason = "PROCESS_NOT_RUNNING"
            elif data.get("invalid_seen") is True:
                reason = "HISTORY_INVALID"
            elif data.get("multiple_seen") is True:
                reason = "HISTORY_MULTIPLE"
            elif data.get("sqlite_seen") is True:
                reason = "HISTORY_SQLITE_UNAVAILABLE"
            elif data.get("bad_seen") is True:
                reason = "HISTORY_OTHER"
            elif data.get("ready_seen") is True:
                reason = "OBSERVED_READY"
            elif data.get("empty_seen") is not True:
                reason = "NO_EMPTY_OBSERVATION"
            elif data.get("final_valid_profiles") != 0:
                reason = "FINAL_VALID_OR_UNKNOWN"
            else:
                reason = "INELIGIBLE_OTHER"
        flags = []
        for label, key in (("invalid", "invalid_seen"), ("sqlite", "sqlite_seen"),
                           ("multiple", "multiple_seen")):
            value = data.get(key)
            flags.append(label + "=" + ("1" if value is True else "0" if value is False else "NA"))
        suffix = ("; PREP_DIAG phase=" + phase + " reason=" + reason
                  + " attempts=" + str(attempts) + " " + " ".join(flags)
                  + " ui=" + ui)
        if len(suffix) <= 512 and suffix.isascii():
            error.args = (args[0] + suffix,)
    except Exception:
        # Malformed diagnostic state must not mask the original failure.
        return


def prepare_profile(
    cli: Path, workspace: Path, model: str, effort: str | None,
    *, terminate, cli_home: Path | None = None, timeout: float = 30,
) -> PreparedProfile:
    """One setup, at most two zero-action initializers; never retry a model request."""
    if not workspace.is_absolute() or workspace.resolve(strict=True) != workspace:
        raise ProposalProfileError("invalid proposal runtime workspace")
    st = workspace.lstat()
    if not stat.S_ISDIR(st.st_mode) or st.st_uid != os.geteuid() or stat.S_IMODE(st.st_mode) != 0o700:
        raise ProposalProfileError("unsafe proposal runtime workspace")
    if (workspace/".git").exists() or (type(timeout) is not int and type(timeout) is not float) or not 20 <= timeout <= 45:
        raise ProposalProfileError("invalid proposal runtime preparation")
    if type(model) is not str or not model or (effort is not None and type(effort) is not str):
        raise ProposalProfileError("invalid proposal runtime model")
    fingerprint = _recovery_cli_fingerprint(cli)
    deadline = fingerprint[1] if fingerprint is not None else None
    recovery_pinned = fingerprint is not None and fingerprint[0] is not None
    validate_hooks(workspace)
    folder = workspace/".agents/agents"/NAME
    _budget_remaining(deadline, 10)
    folder.mkdir(parents=True, mode=0o700)
    _new_file(folder/"agent.md", DEFINITION.encode())
    git = subprocess.run(
        ["/usr/bin/git", "-C", str(workspace), "init", "-q", "--initial-branch=proposal-runtime-fixture"],
        stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        timeout=_budget_remaining(deadline, 10), check=False,
        env={"PATH":"/usr/bin:/bin", "LANG":"C.UTF-8", "GIT_CONFIG_NOSYSTEM":"1", "GIT_CONFIG_GLOBAL":"/dev/null", "GIT_TEMPLATE_DIR":"", "GIT_TERMINAL_PROMPT":"0"},
    )
    if git.returncode != 0:
        raise ProposalProfileError("proposal runtime workspace initialization failed")
    home = cli_home if cli_home is not None else Path.home()/".gemini/antigravity-cli"
    directory = home/"conversations"
    original = _sessions(directory)
    workspace_identity = _recovery_workspace(workspace) if recovery_pinned else None
    first = {}
    try:
        return _initialize_profile_once(cli, workspace, model, effort, terminate=terminate,
            home=home, timeout=timeout, before=original, deadline=deadline, report=first)
    except ProposalProfileError as first_error:
        if not recovery_pinned or not _empty_recovery_eligible(first_error, first):
            _append_preparation_diagnostic(first_error, phase="FIRST", reason="INELIGIBLE",
                attempts=1, report=first, pinned=recovery_pinned)
            raise
        guard = "BUDGET"
        try:
            _budget_remaining(deadline, 1)
            names = first["names"]
            guard = "ROSTER"
            if _sessions(directory) - original != names:
                raise ProposalProfileError("proposal runtime recovery roster drift")
            first_name = next(iter(names))
            guard = "PRISTINE"
            pristine = _pristine_initialization_snapshot(directory, first_name, deadline)
            guard = "WORKSPACE"
            if _recovery_workspace(workspace) != workspace_identity:
                raise ProposalProfileError("proposal runtime recovery workspace drift")
            guard = "CLI_PIN"
            if _recovery_cli_fingerprint(cli, deadline=deadline) != fingerprint:
                raise ProposalProfileError("proposal runtime recovery CLI drift")
            guard = "PRISTINE"
            if _pristine_initialization_snapshot(directory, first_name, deadline) != pristine:
                raise ProposalProfileError("proposal runtime recovery persisted state drift")
            guard = "BUDGET_OR_ROSTER"
            before_second = _sessions(directory)
            if before_second - original != names or _budget_remaining(deadline, timeout + 10) < timeout + 10:
                raise ProposalProfileError("proposal runtime recovery budget or roster unavailable")
        except (OSError, ValueError):
            # Optional recovery never reclassifies or renews the failed first task.
            _append_preparation_diagnostic(first_error, phase="PRE_SECOND", reason=guard,
                attempts=1, report=first, pinned=recovery_pinned)
            raise first_error from None
        second = {}
        try:
            result = _initialize_profile_once(cli, workspace, model, effort, terminate=terminate,
                home=home, timeout=timeout, before=before_second, deadline=deadline, report=second)
        except ProposalProfileError as second_error:
            _append_preparation_diagnostic(second_error, phase="SECOND", reason="INITIALIZER_FAILED",
                attempts=2, report=second, pinned=recovery_pinned)
            raise
        guard = "FINAL_IDENTITY_STATE"
        try:
            global_names = _sessions(directory) - original
            if (not second.get("cleanup_normal") or not second.get("descriptors_closed")
                    or not second.get("process_dead") or len(second.get("names", ())) != 1
                    or result.conversation_id + ".db" not in second["names"]
                    or global_names != names | second["names"]
                    or not 1 <= len(global_names) <= MAX_NEW_SESSIONS
                    or _pristine_initialization_snapshot(directory, first_name, deadline) != pristine
                    or _recovery_workspace(workspace) != workspace_identity):
                raise ProposalProfileError("proposal runtime recovery final identity or state mismatch")
            guard = "BUDGET"
            _budget_remaining(deadline, 5)
            guard = "FINAL_VALIDATE"
            validate_profile(result, fresh=True, cli_home=home, deadline=deadline)
            guard = "FINAL_ROSTER_STATE"
            if (_sessions(directory) - original != global_names
                    or _pristine_initialization_snapshot(directory, first_name, deadline) != pristine):
                raise ProposalProfileError("proposal runtime recovery final state drift")
            guard = "BUDGET"
            _budget_remaining(deadline, 1)
            return result
        except ProposalProfileError as final_error:
            _append_preparation_diagnostic(final_error, phase="FINAL", reason=guard,
                attempts=2, report=second, pinned=recovery_pinned)
            raise


def _initialize_profile_once(
    cli, workspace, model, effort, *, terminate, home, timeout, before, deadline, report,
):
    if _budget_remaining(deadline, timeout + 10) < timeout + 10:
        raise ProposalProfileError("proposal runtime preparation budget exhausted")
    directory = home/"conversations"
    master, slave = pty.openpty()
    termios.tcsetwinsize(master, (30, 120)); os.set_blocking(master, False)
    # Pinned CLI 1.4.2 documents --agent. No dropdown, cursor position, stale
    # rendering or local reselection is used to choose the proposal-only role.
    command = [str(cli), "--mode", "plan", "--sandbox", "--model", model,
               "--agent", NAME, "--add-dir", str(workspace)]
    if effort is not None:
        command += ["--effort", effort]
    process = None
    selector = selectors.DefaultSelector()
    buffer = bytearray()
    trust_accepted = False
    trust_offset = 0
    pending_trust = False
    ready_during_preparation = False
    last_readiness_hint = None
    report.update(empty_seen=False, bad_seen=False, ready_seen=False,
                  invalid_seen=False, sqlite_seen=False, multiple_seen=False,
                  cleanup_normal=False, descriptors_closed=False, process_dead=False)
    preparation_error = None
    preparation_observation = {"capture_state": "UNAVAILABLE"}

    def drain_ui(deadline):
        # Drain the owned nonblocking PTY before AND after metadata reads.
        # Every byte stays under the same cumulative cap and absolute deadline.
        while time.monotonic() < deadline:
            if not any(selector.select(0)):
                return True
            try:
                chunk = os.read(master, min(4096, MAX_UI+1-len(buffer)))
            except BlockingIOError:
                return True
            except OSError:
                return False
            if not chunk:
                return False
            buffer.extend(chunk)
            if len(buffer) > MAX_UI:
                raise ProposalProfileError("proposal runtime UI exceeds limit")
            for query, reply in TERM_REPLIES:
                if query in chunk:
                    os.write(master, reply)
        return False

    def observe_trust():
        nonlocal trust_accepted, trust_offset
        text = buffer[trust_offset:].decode("utf-8", errors="replace")
        normalized = re.sub(r"\x1b\[[0-?]*[ -/]*[@-~]", "", text)
        normalized = re.sub(r"\x1b\][^\x07\x1b]*(?:\x07|\x1b\\)", "", normalized)
        # Ignore an incomplete trailing terminal-control sequence when checking
        # a meaningful partial fixed header; never match a generic word or D/T.
        normalized = re.sub(r"\x1b(?:\[[0-?]*[ -/]*|\][^\x07\x1b]*)?$", "", normalized)
        marker = "Do you trust"
        pending = marker in normalized or any(
            normalized.endswith(marker[:length])
            for length in range(len("Do you"), len(marker))
        )
        if trust_accepted:
            if pending:
                raise ProposalProfileError("proposal runtime unexpected additional trust dialog")
            return False
        choice = trust_choice(text, workspace)
        if choice is not None:
            os.write(master, choice)
            trust_accepted = True
            trust_offset = len(buffer)
            return False
        return pending
    try:
        process = subprocess.Popen(
            command, cwd=workspace, stdin=slave, stdout=slave, stderr=slave,
            start_new_session=True,
            env=dict(os.environ, AGY_CLI_DISABLE_AUTO_UPDATE="true", TERM="xterm-256color"),
        )
        os.close(slave); slave = -1
        selector.register(master, selectors.EVENT_READ)
        started = time.monotonic()
        while process.poll() is None:
            if time.monotonic() >= started + timeout:
                break
            if not drain_ui(started + timeout):
                break
            pending_trust = observe_trust()
            # The hint is never acceptance, nor permission to skip queued UI.
            ready, current_hint = _initialization_readiness_hint(
                directory, before, workspace, model, effort,
                deadline=started + timeout,
            )
            report["empty_seen"] |= (current_hint["new_sessions"] == 1 and current_hint["empty_profiles"] == 1)
            report["bad_seen"] |= bool(current_hint["invalid_profiles"] or current_hint["sqlite_unavailable"] or current_hint["new_sessions"] > 1)
            report["invalid_seen"] |= bool(current_hint["invalid_profiles"])
            report["sqlite_seen"] |= bool(current_hint["sqlite_unavailable"])
            report["multiple_seen"] |= current_hint["new_sessions"] > 1
            report["ready_seen"] |= bool(ready or current_hint["valid_profiles"])
            if current_hint["reason"] == "DEADLINE":
                break
            last_readiness_hint = current_hint
            if ready:
                if not drain_ui(started + timeout):
                    break
                pending_trust = observe_trust()
                if not pending_trust and time.monotonic() < started + timeout:
                    ready_during_preparation = True
                    break
            # No quiet-period timer and no extension: pending trust must resolve
            # from actual newly drained bytes before the original deadline.
            selector.select(0.1)
        if pending_trust:
            raise ProposalProfileError("proposal runtime trust dialog incomplete")
    except ProposalProfileError as error:
        preparation_error = error
        raise
    finally:
        try:
            try:
                preparation_observation = _preparation_failure_observation(
                    buffer, process, workspace, trust_accepted, pending_trust,
                    ready_during_preparation,
                )
            except Exception:
                # Diagnostics must never replace the preparation/cleanup failure.
                preparation_observation = {"capture_state": "UNAVAILABLE"}
            if preparation_error is not None:
                preparation_error.preparation_observation = preparation_observation
        finally:
            cleanup_error = None
            try:
                if process is not None:
                    terminate(process)
            except BaseException as error:
                cleanup_error = error
            close_error = None
            actions = [selector.close, lambda: os.close(master)]
            if slave >= 0:
                actions.append(lambda: os.close(slave))
            for close in actions:
                try:
                    close()
                except BaseException as error:
                    if close_error is None:
                        close_error = error
            report["descriptors_closed"] = close_error is None
            report["cleanup_normal"] = cleanup_error is None and close_error is None
            try:
                report["process_dead"] = process is not None and process.poll() is not None
            except Exception:
                report["process_dead"] = False
            buffer.clear()  # UI/auth prose is neither logged nor retained.
            if cleanup_error is not None:
                raise cleanup_error
            if close_error is not None:
                raise close_error
    _budget_remaining(deadline, 5)
    names = _sessions(directory)-before
    report["names"] = names
    if not (1 <= len(names) <= MAX_NEW_SESSIONS):
        error = ProposalProfileError("proposal runtime fresh session discovery failed")
        error.preparation_observation = preparation_observation
        raise error
    matches = []
    for name in sorted(names):
        candidate = PreparedProfile(name[:-3], workspace, model, effort)
        try:
            options = {"fresh": True, "cli_home": home}
            if deadline is not None:
                options["deadline"] = deadline
            validate_profile(candidate, **options)
        except ProposalProfileError:
            continue
        matches.append(candidate)
    report["final_valid_profiles"] = len(matches)
    _budget_remaining(deadline, 5)
    if len(matches) != 1 or not ready_during_preparation:
        # Metadata published only during cleanup cannot create eligibility.
        reason = ("proposal runtime selected session is ambiguous or absent" if len(matches) != 1
                  else "proposal runtime profile was not ready during bounded preparation")
        error = ProposalProfileError(reason)
        error.preparation_observation = preparation_observation
        if last_readiness_hint is not None:
            error.observation = {"last_initialization_readiness_hint": last_readiness_hint,
                                 "final_new_sessions": len(names), "final_valid_profiles": len(matches),
                                 "ready_during_preparation": ready_during_preparation}
            # A last hint is not current/final acceptance. Counts only, no payload.
            if last_readiness_hint["empty_profiles"]:
                error.args = (str(error) + "; LAST_HINT_INITIAL_METADATA_EMPTY"
                              + " new=" + str(last_readiness_hint["new_sessions"])
                              + " empty=" + str(last_readiness_hint["empty_profiles"])
                              + " final_valid=" + str(len(matches)),)
        raise error
    return matches[0]
